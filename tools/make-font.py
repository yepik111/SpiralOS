def contours(strokes,W):
    h=W/2; out=[]
    def orient(pts):
        a=sum(x1*y2-x2*y1 for (x1,y1),(x2,y2) in zip(pts,pts[1:]+pts[:1]))
        return pts if a<0 else pts[::-1]
    for pl in strokes:
        for a,b in zip(pl,pl[1:]):
            dx,dy=b[0]-a[0],b[1]-a[1]; l=math.hypot(dx,dy)
            if l<0.01: continue
            nx,ny=-dy/l*h,dx/l*h
            out.append(orient([(a[0]+nx,a[1]+ny),(b[0]+nx,b[1]+ny),(b[0]-nx,b[1]-ny),(a[0]-nx,a[1]-ny)]))
        for p in pl: out.append(orient([(p[0]+h*math.cos(2*math.pi*i/10),p[1]+h*math.sin(2*math.pi*i/10)) for i in range(10)]))
    return out
def build(style,W,out,mono=False):
    bold=style=="Bold"; names=[".notdef"]; cmap={}; glyphs={}; adv={}
    def add(name,a,strokes):
        if mono:
            xs_=[x for sk in strokes for x,y in sk]
            if xs_:
                lo,hi=min(xs_),max(xs_); k=min(1.0,(540-W)/max(1,hi-lo)); c=(lo+hi)/2
                strokes=[[((x-c)*k+300,y) for x,y in sk] for sk in strokes]
            a=600
        else:
            PAD=28 if bold else 24; strokes=[[(x+PAD,y) for x,y in sk] for sk in strokes]; a=a+2*PAD
        pen=TTGlyphPen(None); xs=[]
        for c in contours(strokes,W):
            pts=[(round(x),round(y)) for x,y in c]; xs+= [p[0] for p in pts]
            pen.moveTo(pts[0]); [pen.lineTo(p) for p in pts[1:]]; pen.closePath()
        glyphs[name]=pen.glyph(); adv[name]=(a,min(xs) if xs else 0); names.append(name) if name!=".notdef" else None
    add(".notdef",600,[P(70,0,70,700,530,700,530,0,70,0)])
    for ch,(a,st) in G.items():
        n="uni%04X"%ord(ch); add(n,a,st); cmap[ord(ch)]=n
    fb=FontBuilder(1000,isTTF=True); fb.setupGlyphOrder(names); fb.setupCharacterMap(cmap); fb.setupGlyf(glyphs); fb.setupHorizontalMetrics(adv)
    fb.setupHorizontalHeader(ascent=800,descent=-250)
    fam="Spiral Mono" if mono else "Spiral Sans"; fid=fam.replace(" ",""); fb.setupNameTable({"familyName":fam,"styleName":style,"uniqueFontIdentifier":fid+"-"+style,"fullName":fam+" "+style,"psName":fid+"-"+style,"version":"Version 1.0","copyright":"Copyright (c) 2026 SpiralOS"})
    fb.setupOS2(sTypoAscender=800,sTypoDescender=-250,sTypoLineGap=0,usWinAscent=950,usWinDescent=320,sxHeight=480,sCapHeight=700,usWeightClass=700 if bold else 400,fsSelection=0x20 if bold else 0x40)
    fb.setupPost(isFixedPitch=1 if mono else 0); fb.font["head"].macStyle=1 if bold else 0
    fb.save(out); print("geschrieben:",out,len(names),"Glyphen")
